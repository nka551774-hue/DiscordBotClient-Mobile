import 'package:flutter/foundation.dart';
import 'package:shared_preferences/shared_preferences.dart';

/// UI language: 'zh' (the source strings), 'en' or 'ja'.
class AppLanguage {
  static const _prefKey = 'app_language';
  static final ValueNotifier<String> current = ValueNotifier<String>('zh');

  static Future<void> load() async {
    final prefs = await SharedPreferences.getInstance();
    final saved = prefs.getString(_prefKey);
    if (saved != null && options.containsKey(saved)) current.value = saved;
  }

  static Future<void> set(String lang) async {
    if (!options.containsKey(lang)) return;
    current.value = lang;
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString(_prefKey, lang);
  }

  static const Map<String, String> options = {
    'zh': '中文',
    'en': 'English',
    'ja': '日本語',
  };
}

/// Translates a Chinese source string; falls back to it when untranslated.
String tr(String zh) {
  switch (AppLanguage.current.value) {
    case 'en':
      return _en[zh] ?? zh;
    case 'ja':
      return _ja[zh] ?? zh;
    default:
      return zh;
  }
}

/// [tr] for templates with {0}, {1}… placeholders.
String trf(String zhTemplate, List<Object?> args) {
  var s = tr(zhTemplate);
  for (var i = 0; i < args.length; i++) {
    s = s.replaceAll('{$i}', '${args[i]}');
  }
  return s;
}

